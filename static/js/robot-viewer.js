// Interactive 3D robot/trajectory viewer — Three.js + urdf-loader
//
// ── What you need to provide ─────────────────────────────────────────────────
//
//   1. A URDF (+ STL/DAE/OBJ meshes) per robot, registered in the ROBOTS map
//      below keyed by the results/<robot> dir name. Each entry is
//      { urdf: '<url>', packages: { NAME: '<dir url>' } } — `packages` maps any
//      package://NAME/... URIs to a directory (leave {} for plain relative refs).
//
//   2. results/trials.json + per-sample trajectory.json (run tools/make_plans.py).
//      trajectory.json: { "joint_names": [...], "frames": [[q0, q1, ...], ...] }
//      and its joint_names must match the robot's URDF joint names.
//
//   3. Optional per-trial scene clouds (XYZ or XYZ+RGB PLY) listed in trials.json;
//      flat-colored by SCENE_COLORS when they carry no per-vertex color.
//
//   4. Optional robot base transform: set ROBOT_BASE_MATRIX to a 16-element
//      column-major Float array matching a THREE.Matrix4, or leave null for
//      identity.
//
// ─────────────────────────────────────────────────────────────────────────────

import * as THREE from 'three';
import { OrbitControls } from 'three/addons/controls/OrbitControls.js';
import { PLYLoader }     from 'three/addons/loaders/PLYLoader.js';
// urdf-loader is vendored locally (static/vendor/urdf-loader). Its internal
// `three/examples/jsm/...` mesh-loader imports resolve via the import-map in
// index.html, so it shares the same Three.js instance — no runtime CDN.
import URDFLoader from 'urdf-loader';

// ── Config ────────────────────────────────────────────────────────────────────
// URDF per robot (trials.json carries each trial's `robot`). Mesh refs in both
// URDFs are plain relative paths that resolve next to the .urdf, so no package://
// roots are needed. Add new robots here keyed by their results/<robot> dir name.
const ROBOTS = {
  rby1:   { urdf: './results/rbyxhand_modified/robot_model_rm_capsule.urdf', packages: {} },
  franka: { urdf: './results/robot_models/panda.urdf',                       packages: {} },
};
// Results root + trials manifest (generated by tools/make_plans.py). trials.json
// nests trial → sample → plan (labels, frames, scores, paths) plus each trial's
// shared scene clouds; per-plan trajectory.json files are fetched on demand.
const RESULTS_ROOT    = './results/';
const TRIALS_URL      = RESULTS_ROOT + 'trials.json';
// Fixed tint per scene-cloud basename (PLYs are XYZ-only, no per-vertex color).
const SCENE_COLORS    = {
  'static_scene.ply': 0x9aa0a6, // scene  = grey
  'tool.ply':         0xff8c2b, // tool   = orange
  'target.ply':       0x2bcc63, // target = green
  'box1.ply':         0x4f8cff, // box 1  = blue
  'box2.ply':         0xb04fff, // box 2  = purple
};
const SCENE_COLOR_DEFAULT = 0x3a8cc1;
const PLAYBACK_FPS    = 10;
const POINT_SIZE      = 0.008;   // world-space radius; tune to your scene scale
const ROBOT_BASE_MATRIX = null; // null = identity; else 16-element column-major array
// ─────────────────────────────────────────────────────────────────────────────

class RobotViewer {
  constructor(containerId) {
    this._container = document.getElementById(containerId);
    this._canvas    = this._container.querySelector('canvas');

    this._renderer = new THREE.WebGLRenderer({ canvas: this._canvas, antialias: true });
    this._renderer.setPixelRatio(Math.min(window.devicePixelRatio, 2));
    this._renderer.outputColorSpace = THREE.SRGBColorSpace;

    this._scene = new THREE.Scene();
    this._scene.background = new THREE.Color(0xf0f0f0);

    this._camera = new THREE.PerspectiveCamera(55, 1, 0.005, 200);
    this._camera.position.set(2, 1.5, 2);

    this._controls = new OrbitControls(this._camera, this._canvas);
    this._controls.enableDamping = true;

    // Lighting
    this._scene.add(new THREE.AmbientLight(0xffffff, 0.7));
    const sun = new THREE.DirectionalLight(0xffffff, 1.0);
    sun.position.set(5, 10, 5);
    this._scene.add(sun);
    const fill = new THREE.DirectionalLight(0xffffff, 0.3);
    fill.position.set(-5, 3, -5);
    this._scene.add(fill);

    // Source data is Z-up (ROS convention) but three.js is Y-up. Parent the
    // robot + point clouds to a world group rotated -90° about X so Z→Y and
    // the robot stands upright with the default Y-up camera/controls.
    this._world = new THREE.Group();
    this._world.rotation.x = -Math.PI / 2;
    this._scene.add(this._world);
    this._world.add(new THREE.AxesHelper(0.2));

    this._robot     = null;   // currently shown URDF robot
    this._robots    = {};      // name → loaded URDFRobot (cached, kept in world)
    this._robotName = null;
    this._pcds   = [];
    this._traj   = null;
    this._frame  = 0;
    this._playing   = false;
    this._playTimer = null;

    // Selection hierarchy: trial → sample (one plan per sample, from trials.json).
    this._trials       = [];
    this._trialButtons = [];
    this._activeTrial  = -1;
    this._dataRoot     = null; // current trial's root URL

    this._samples       = []; // current trial's samples (each with cached _traj)
    this._sampleButtons = [];
    this._activeSample  = -1;

    this._elStatus  = document.getElementById('rv-status');
    this._elSlider  = document.getElementById('rv-slider');
    this._elLabel   = document.getElementById('rv-frame-label');
    this._elPlay    = document.getElementById('rv-btn-play');
    this._elTrials  = document.getElementById('rv-trials');
    this._elSamples = document.getElementById('rv-samples');
    this._elPcd     = document.getElementById('rv-btn-pcd');
    this._elRobot   = document.getElementById('rv-btn-robot');
    this._elRgb     = document.getElementById('rv-rgb');

    this._bindUI();
    this._resize();
    window.addEventListener('resize', () => this._resize());
    this._renderLoop();
  }

  async load() {
    try {
      this._status('Loading trials…');
      const resp = await fetch(TRIALS_URL);
      if (!resp.ok) throw new Error(`HTTP ${resp.status} fetching trials.json`);
      const manifest = await resp.json();
      this._trials = manifest.trials || [];
      if (!this._trials.length) throw new Error('trials.json lists no trials');
      this._buildTrialButtons();

      await this._selectTrial(0);             // loads robot + scene + first sample
      this._elStatus.style.display = 'none';
    } catch (err) {
      this._status(`Error: ${err.message}`, '#c00');
      console.error('[RobotViewer]', err);
    }
  }

  _buildTrialButtons() {
    if (!this._elTrials) return;
    this._elTrials.innerHTML = '';
    this._elTrials.appendChild(this._rowLabel('Trial:'));
    this._trialButtons = this._trials.map((t, i) => {
      const btn = document.createElement('button');
      btn.className = 'button is-small';
      btn.textContent = t.label;
      btn.title = `${t.id} — ${t.samples?.length || 0} samples`;
      btn.addEventListener('click', () => this._guard(this._selectTrial(i)));
      this._elTrials.appendChild(btn);
      return btn;
    });
  }

  async _selectTrial(i) {
    const t = this._trials[i];
    if (!t || i === this._activeTrial) return;
    this._activeTrial = i;
    this._trialButtons.forEach((b, k) => b.classList.toggle('is-dark', k === i));
    this._dataRoot = RESULTS_ROOT + t.root;

    // per-trial reference image in the top-left corner (hidden if none)
    if (this._elRgb) {
      if (t.rgb) {
        this._elRgb.src = this._dataRoot + t.rgb;
        this._elRgb.style.display = '';
      } else {
        this._elRgb.removeAttribute('src');
        this._elRgb.style.display = 'none';
      }
    }

    await this._ensureRobot(t.robot);          // swap URDF if this trial's robot differs

    // Scene clouds are shared across a trial's samples — (re)load them once here.
    this._status('Loading point cloud…');
    await this._loadPCD(t.scene);

    this._samples = t.samples || [];
    this._buildSampleButtons();

    this._status('Loading trajectory…');
    this._activeSample = -1;                   // force (re)select for the new trial
    await this._selectSample(0);

    this._fitCamera();                         // scene changed → reframe
    this._elStatus.style.display = 'none';
  }

  _buildSampleButtons() {
    if (!this._elSamples) return;
    this._elSamples.innerHTML = '';
    this._elSamples.appendChild(this._rowLabel('Sample:'));
    this._sampleButtons = this._samples.map((s, i) => {
      const btn = document.createElement('button');
      btn.className = 'button is-small';
      const score = (s.score != null)
        ? `<span style="opacity:.55; margin-left:.4em; font-variant-numeric:tabular-nums;">${s.score.toFixed(2)}</span>`
        : '';
      btn.innerHTML = `${s.label}${score}`;
      btn.title = `${s.id} — ${s.frames} frames`
                + (s.score != null ? `, score ${s.score}` : '');
      btn.addEventListener('click', () => this._guard(this._selectSample(i)));
      this._elSamples.appendChild(btn);
      return btn;
    });
  }

  async _selectSample(i) {
    const s = this._samples[i];
    if (!s || i === this._activeSample) return;
    this._activeSample = i;
    this._sampleButtons.forEach((b, k) => b.classList.toggle('is-dark', k === i));

    if (!s._traj) {
      const resp = await fetch(this._dataRoot + s.trajectory);
      if (!resp.ok) throw new Error(`HTTP ${resp.status} fetching ${s.trajectory}`);
      s._traj = await resp.json();   // cache so re-selecting is instant
    }
    this._traj = s._traj;
    this._elSlider.max = Math.max(0, this._traj.frames.length - 1);
    this._setFrame(0);               // also refreshes the frame label
  }

  // Small grey caption that precedes a row of buttons.
  _rowLabel(text) {
    const span = document.createElement('span');
    span.textContent = text;
    span.className = 'is-size-7 has-text-grey';
    span.style.marginRight = '.15rem';
    return span;
  }

  // Run a promise from a UI handler, surfacing any error in the status box.
  _guard(promise) {
    Promise.resolve(promise).catch(err => {
      this._status(`Error: ${err.message}`, '#c00');
      console.error('[RobotViewer]', err);
    });
  }

  _clearPCD() {
    for (const p of this._pcds) {
      this._world.remove(p);
      p.geometry.dispose();
      p.material.dispose();
    }
    this._pcds = [];
  }

  _loadPCD(sceneFiles) {
    this._clearPCD();                 // drop the previous trial's clouds
    if (this._elPcd) this._elPcd.textContent = 'Hide Cloud';
    const loader = new PLYLoader();
    return Promise.all((sceneFiles || []).map(file => new Promise((resolve, reject) => {
      loader.load(this._dataRoot + file, geo => {
        const hasColor = geo.hasAttribute('color');
        const base = file.split('/').pop();
        const pts = new THREE.Points(geo, new THREE.PointsMaterial({
          size: POINT_SIZE,
          sizeAttenuation: true,
          vertexColors: hasColor,
          color: hasColor ? 0xffffff : (SCENE_COLORS[base] ?? SCENE_COLOR_DEFAULT),
        }));
        this._pcds.push(pts);
        this._world.add(pts);
        resolve();
      }, undefined, reject);
    })));
  }

  // Load (once) and show the URDF for `name`; hide the others. Robots are cached
  // and kept in the world group so switching back is instant.
  async _ensureRobot(name) {
    if (!this._robots[name]) {
      const cfg = ROBOTS[name];
      if (!cfg) throw new Error(`no URDF configured for robot "${name}"`);
      this._status('Loading robot…');
      this._robots[name] = await this._loadRobotURDF(cfg);
      this._world.add(this._robots[name]);
    }
    for (const [n, r] of Object.entries(this._robots)) r.visible = (n === name);
    this._robot = this._robots[name];
    this._robotName = name;
    if (this._elRobot) this._elRobot.textContent = 'Hide Robot';
  }

  _loadRobotURDF(cfg) {
    return new Promise((resolve, reject) => {
      const loader = new URDFLoader();
      loader.packages = cfg.packages || {};
      loader.load(cfg.urdf, robot => {
        if (ROBOT_BASE_MATRIX) {
          robot.applyMatrix4(new THREE.Matrix4().fromArray(ROBOT_BASE_MATRIX));
        }
        resolve(robot);
      }, undefined, reject);
    });
  }

  _setFrame(idx) {
    if (!this._traj) return;
    const n = this._traj.frames.length;
    idx = Math.max(0, Math.min(idx, n - 1));
    this._frame = idx;

    if (this._robot) {
      const q     = this._traj.frames[idx];
      const names = this._traj.joint_names;
      names.forEach((name, i) => {
        const joint = this._robot.joints?.[name];
        if (joint) joint.setJointValue(q[i]);
      });
    }

    this._elSlider.value = idx;
    this._labelFrame(idx, n);
  }

  _fitCamera() {
    this._scene.updateMatrixWorld(true);   // apply world-group rotation first
    const box = new THREE.Box3();
    this._scene.traverseVisible(obj => {
      if (obj.isMesh || obj.isPoints) box.expandByObject(obj);
    });
    if (box.isEmpty()) return;
    const center = box.getCenter(new THREE.Vector3());
    const radius = box.getSize(new THREE.Vector3()).length() * 0.8;
    this._camera.position.copy(center).addScaledVector(
      new THREE.Vector3(1, 0.7, 1).normalize(), radius * 1.45,
    );
    this._controls.target.copy(center);
    this._controls.update();
  }

  _bindUI() {
    this._elSlider.addEventListener('input', e => this._setFrame(+e.target.value));

    this._elPlay.addEventListener('click', () => {
      this._playing = !this._playing;
      this._elPlay.textContent = this._playing ? '⏸ Pause' : '▶ Play';
      if (this._playing) {
        this._playTimer = setInterval(() => {
          const n = this._traj?.frames.length || 1;
          this._setFrame((this._frame + 1) % n);
        }, 1000 / PLAYBACK_FPS);
      } else {
        clearInterval(this._playTimer);
      }
    });

    document.getElementById('rv-btn-robot').addEventListener('click', e => {
      if (this._robot) {
        this._robot.visible = !this._robot.visible;
        e.currentTarget.textContent = this._robot.visible ? 'Hide Robot' : 'Show Robot';
      }
    });

    document.getElementById('rv-btn-pcd').addEventListener('click', e => {
      if (this._pcds.length) {
        const vis = !this._pcds[0].visible;
        this._pcds.forEach(p => { p.visible = vis; });
        e.currentTarget.textContent = vis ? 'Hide Cloud' : 'Show Cloud';
      }
    });

    document.getElementById('rv-btn-fit').addEventListener('click', () => this._fitCamera());
  }

  _status(msg, color = '#555') {
    this._elStatus.textContent = msg;
    this._elStatus.style.color = color;
    this._elStatus.style.display = '';
  }

  _labelFrame(idx, total) {
    this._elLabel.textContent = `${idx} / ${Math.max(0, total - 1)}`;
  }

  _resize() {
    const w = this._container.clientWidth;
    const h = this._container.clientHeight;
    this._renderer.setSize(w, h, false);
    this._camera.aspect = w / h;
    this._camera.updateProjectionMatrix();
  }

  _renderLoop() {
    requestAnimationFrame(() => this._renderLoop());
    this._controls.update();
    this._renderer.render(this._scene, this._camera);
  }
}

new RobotViewer('rv-container').load();
